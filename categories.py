def is_question_message(text: str) -> bool:
    """Определяет, является ли сообщение вопросом/обращением клиента."""
    if not text:
        return False
    lower = text.lower().strip()
    if "?" in lower:
        return True
    return any(trig in lower for trig in QUESTION_TRIGGERS)


def classify_text(text: str) -> Tuple[str, str]:
    """
    Классифицирует текст по категории боли/темы.
    Возвращает (category_key, category_title).
    Если совпадений нет, возвращает ('other', '❓ Прочие вопросы').
    """
    if not text:
        return "other", "❓ Прочие вопросы"
    
    lower = text.lower()
    scores: Dict[str, int] = {}
    
    for cat_key, cat_data in CATEGORIES_DEF.items():
        score = 0
        for kw in cat_data["keywords"]:
            if kw in lower:
                score += 1
        if score > 0:
            scores[cat_key] = score
            
    if not scores:
        return "other", "❓ Прочие вопросы"
        
    best_cat = max(scores.items(), key=lambda x: x[1])[0]
    return best_cat, CATEGORIES_DEF[best_cat]["title"]
